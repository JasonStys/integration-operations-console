/**
 * File: generate-code-index.mjs
 * Purpose: Generate exact, reviewable line locations for source declarations and important variables.
 * Symbols: patterns constant, sourceFiles/walk/extract/render/main functions.
 * Variables: --check compares generated text with the committed index without writing files.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(repositoryRoot, 'docs', 'code-index.md');
const supportedExtensions = new Set(['.java', '.ts', '.tsx', '.mjs', '.sh']);
const excludedNames = new Set(['schema.d.ts', 'mvnw']);
const patterns = [
  /\b(?:class|interface|record|enum)\s+([A-Za-z_$][\w$]*)/,
  /\b(?:public|protected|private)\s+(?:static\s+)?(?:synchronized\s+)?[\w<>?,.\[\] ]+\s+([a-zA-Z_$][\w$]*)\s*\(/,
  /\b(?:function)\s+([A-Za-z_$][\w$]*)\s*\(/,
  /\b(?:const|let|readonly)\s+([A-Za-z_$][\w$]*)\b/,
  /^([A-Za-z_][\w]*)\(\)\s*\{/,
];

/** Recursively finds authored source files and keeps generated declarations out of the index. */
function walk(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      return ['.git', 'coverage', 'dist', 'node_modules', 'target'].includes(entry.name)
        ? []
        : walk(path);
    }
    return supportedExtensions.has(extname(path)) && !excludedNames.has(entry.name) ? [path] : [];
  });
}

/** Extracts the first named declaration matched on each physical source line. */
function extract(path) {
  return readFileSync(path, 'utf8')
    .split(/\r?\n/)
    .flatMap((line, index) => {
      for (const pattern of patterns) {
        const match = line.match(pattern);
        if (match) return [{ line: index + 1, name: match[1] }];
      }
      return [];
    });
}

/** Renders stable Markdown so code reviews clearly show declaration movement. */
function render() {
  const lines = [
    '# Code index',
    '',
    'Generated by `scripts/generate-code-index.mjs`. Line numbers identify classes, functions,',
    'methods, and important named variables. Run the generator after source edits.',
    '',
  ];
  for (const path of walk(repositoryRoot).sort()) {
    const declarations = extract(path);
    if (declarations.length === 0) continue;
    const repositoryPath = relative(repositoryRoot, path).replaceAll('\\', '/');
    lines.push(`## \`${repositoryPath}\``, '');
    for (const declaration of declarations) {
      lines.push(`- Line ${declaration.line}: \`${declaration.name}\``);
    }
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

/** Writes the index, or verifies exact freshness when invoked with --check. */
function main() {
  const generated = render();
  if (process.argv.includes('--check')) {
    if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== generated) {
      console.error('docs/code-index.md is stale; run node scripts/generate-code-index.mjs');
      process.exitCode = 1;
      return;
    }
    console.log('Code index is current.');
    return;
  }
  writeFileSync(outputPath, generated, 'utf8');
  console.log('Generated docs/code-index.md.');
}

main();
